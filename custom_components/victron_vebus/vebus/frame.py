"""Frame encoding and stream decoding for the MK2/MK3 serial protocol (section 3.2).

A frame on the wire is::

    <length> <marker> <command/data ...> <checksum>

``length`` counts every byte between itself and the checksum. Bit 7 of the length
byte flags appended LED status and is masked off. The checksum makes the sum of
all bytes of the frame, including length and checksum, equal to zero modulo 256.

Frames generated by the interface itself use marker ``0xFF`` followed by an ASCII
command letter. VE.Bus frames forwarded by the interface (info frames, the
MasterMultiLED frame, ...) use other marker bytes.
"""

from __future__ import annotations

from dataclasses import dataclass

from .const import (
    MARKER_BOOT,
    MARKER_INFO,
    MARKER_MASTER_MULTI_LED,
    MARKER_MK,
    MARKER_PANEL,
    MAX_FRAME_LENGTH,
)

KNOWN_MARKERS = frozenset(
    {MARKER_MK, MARKER_INFO, MARKER_MASTER_MULTI_LED, MARKER_PANEL, MARKER_BOOT}
)


def checksum(data: bytes) -> int:
    """Return the checksum byte for ``data`` (which includes the length byte)."""
    return -sum(data) & 0xFF


def encode_frame(command: int, data: bytes | bytearray | list[int] = b"") -> bytes:
    """Encode an interface command frame (marker 0xFF)."""
    body = bytes([MARKER_MK, command]) + bytes(data)
    head = bytes([len(body)]) + body
    return head + bytes([checksum(head)])


@dataclass(frozen=True, slots=True)
class Frame:
    """A decoded frame without its length and checksum bytes."""

    marker: int
    payload: bytes

    @property
    def is_mk(self) -> bool:
        """Return True if the frame was generated by the interface itself."""
        return self.marker == MARKER_MK

    @property
    def command(self) -> int | None:
        """Return the command letter of an interface frame."""
        if self.is_mk and self.payload:
            return self.payload[0]
        return None

    @property
    def data(self) -> bytes:
        """Return the data of the frame (after the command letter for MK frames)."""
        if self.is_mk:
            return self.payload[1:]
        return self.payload

    @classmethod
    def from_body(cls, body: bytes) -> Frame:
        """Create a frame from the bytes between length and checksum."""
        return cls(marker=body[0], payload=bytes(body[1:]))

    def to_bytes(self) -> bytes:
        """Re-encode the frame, used for diagnostics."""
        head = bytes([len(self.payload) + 1, self.marker]) + self.payload
        return head + bytes([checksum(head)])


class FrameDecoder:
    """Incremental decoder that splits a byte stream into frames.

    Invalid data is skipped one byte at a time until a valid frame boundary is
    found again, so the decoder recovers from noise and from starting in the
    middle of a frame.
    """

    def __init__(self) -> None:
        """Initialize the decoder."""
        self._buffer = bytearray()
        self.discarded_bytes = 0
        self.checksum_errors = 0

    def reset(self) -> None:
        """Drop any buffered data."""
        self._buffer.clear()

    def feed(self, data: bytes) -> list[Frame]:
        """Add received bytes and return all complete frames."""
        self._buffer.extend(data)
        frames: list[Frame] = []
        buf = self._buffer
        while buf:
            length = buf[0] & 0x7F
            if length == 0 or length > MAX_FRAME_LENGTH:
                del buf[0]
                self.discarded_bytes += 1
                continue
            total = length + 2
            if len(buf) < total:
                # Either a frame that is still arriving or a garbage length byte.
                # If a complete, plausible frame starts later in the buffer the
                # first byte was garbage, so skip ahead instead of stalling.
                if len(buf) < 2 or buf[1] in KNOWN_MARKERS:
                    break
                skip = self._find_frame_start(1)
                if skip is None:
                    break
                del buf[:skip]
                self.discarded_bytes += skip
                continue
            candidate = buf[:total]
            if sum(candidate) & 0xFF:
                # Not a frame boundary (or a corrupted frame): resynchronise.
                del buf[0]
                self.discarded_bytes += 1
                self.checksum_errors += 1
                continue
            frames.append(Frame.from_body(bytes(candidate[1:-1])))
            del buf[:total]
        return frames

    def _find_frame_start(self, start: int) -> int | None:
        """Return the offset of the first complete frame with a known marker."""
        buf = self._buffer
        for pos in range(start, len(buf) - 2):
            length = buf[pos] & 0x7F
            total = length + 2
            if (
                0 < length <= MAX_FRAME_LENGTH
                and pos + total <= len(buf)
                and buf[pos + 1] in KNOWN_MARKERS
                and not sum(buf[pos : pos + total]) & 0xFF
            ):
                return pos
        return None
